  doc.text(`Total Outflows: ${expense.toLocaleString()} RWF`, margin + 175, y + 22);
  doc.setTextColor(11, 93, 59);
  doc.text(`Net Treasury Balance: ${balance.toLocaleString()} RWF`, margin + 335, y + 22);

